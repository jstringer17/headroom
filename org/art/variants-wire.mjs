// Copies org/art/variants-prompts.json into sitemaker/src/cine-kit.js (between
// the VARIANTS markers), verbatim: label, headline, accent and prompt per slot.
// Run: node org/art/variants-wire.mjs, then node org/art/kit-doc.mjs.
import { readFileSync, writeFileSync } from "fs";
const src = JSON.parse(readFileSync(new URL("./variants-prompts.json", import.meta.url), "utf8"));
const kitPath = new URL("../../sitemaker/src/cine-kit.js", import.meta.url);
// CEO rule: every prompt says 16:9. The edit prompts in the JSON leave it out,
// so it is added in front of their "No people" line (nothing else changes).
const r169 = (p) => p.includes("16:9") ? p : p.replace(/\s*No people,/, " Wide 16:9 photo. No people,");
const DEFAULT = { roofing: ["shingle", "Asphalt shingle"], fencing: ["cedar", "Cedar privacy"], pressure: ["driveway", "Driveway and walkway"] };
let block = "// VARIANTS:BEGIN (generated by org/art/variants-wire.mjs from variants-prompts.json; do not edit by hand)\n";
for (const [trade, list] of Object.entries(src)) {
  const vs = [{ key: DEFAULT[trade][0], label: DEFAULT[trade][1], default: true }];
  for (const v of list) {
    const it = Object.fromEntries(v.items.map((i) => [i.slot, i]));
    for (const s of ["s1", "s2", "s3", "s4", "before", "after"]) if (!it[s] || !it[s].prompt) throw new Error(`${trade}/${v.key}: missing ${s}`);
    vs.push({
      key: v.key, label: v.label,
      story: ["s1", "s2", "s3", "s4"].map((s) => ({ id: `${v.key}/${s}`, headline: it[s].headline, accent: it[s].accent, prompt: r169(it[s].prompt) })),
      beforeAfter: { title: v.title || `Before and after: ${v.label.toLowerCase()}.`,
        before: { id: `${v.key}/before`, prompt: r169(it.before.prompt) }, after: { id: `${v.key}/after`, prompt: r169(it.after.prompt) } },
    });
  }
  block += `CINE_KIT.${trade}.variants = ${JSON.stringify(vs, null, 1)};\n`;
}
block += "// VARIANTS:END";
const kit = readFileSync(kitPath, "utf8");
const out = kit.replace(/\/\/ VARIANTS:BEGIN[\s\S]*?\/\/ VARIANTS:END/, block);
if (out === kit && !kit.includes(block)) throw new Error("VARIANTS markers not found");
writeFileSync(kitPath, out);
console.log("wired", Object.values(src).reduce((n, l) => n + l.length, 0), "variants");
