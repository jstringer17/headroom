// The built-in picture library (sitemaker/library) for hosted DEMO sites.
//   node hosting/scripts/upload-library.mjs            # write hosting/src/library-index.js + print the upload commands (no upload)
//   node hosting/scripts/upload-library.mjs --local    # also upload to local (wrangler dev) R2
//   node hosting/scripts/upload-library.mjs --remote   # also upload to the real R2 bucket (chief of staff, after CEO ok)
// Files land in R2 at library/<trade>/<slotId>.<ext> (variant slots: library/<trade>/<variant>/<slot>.<ext>); the Worker serves GET /library/*.
// CEO rule: library pictures are sample-site only. render.js uses them only for sites marked as demo (form.library or form.hosting.demo).
import { readdirSync, statSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
export const LIB_DIR = resolve(root, "..", "sitemaker", "library");
export const INDEX_FILE = join(root, "src", "library-index.js");
export const TYPES = { webp: "image/webp", jpg: "image/jpeg", jpeg: "image/jpeg", png: "image/png" };
export const CACHE = "public, max-age=2592000";

// trade -> { slotId: "trade/slot.ext" }, same walk as sitemaker/build.mjs.
export function scanLibrary(dir = LIB_DIR) {
  const index = {};
  if (!existsSync(dir)) return index;
  const add = (trade, slot, file) => { (index[trade] = index[trade] || {})[slot] = file; };
  for (const trade of readdirSync(dir).sort()) {
    const tdir = join(dir, trade);
    if (!statSync(tdir).isDirectory()) continue;
    for (const entry of readdirSync(tdir).sort()) {
      const full = join(tdir, entry);
      if (statSync(full).isDirectory()) {
        for (const f of readdirSync(full).sort()) {
          const m = /^([a-z0-9-]+)\.(webp|jpe?g|png)$/i.exec(f);
          if (m) add(trade, `${entry}/${m[1]}`, `${trade}/${entry}/${f}`);
        }
      } else {
        const m = /^([a-z0-9-]+)\.(webp|jpe?g|png)$/i.exec(entry);
        if (m) add(trade, m[1], `${trade}/${entry}`);
      }
    }
  }
  return index;
}

// Width and height of a webp, png or jpeg file (null when unknown).
export function imageSize(buf) {
  if (buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") {
    const kind = buf.toString("ascii", 12, 16);
    if (kind === "VP8X") return { w: 1 + buf.readUIntLE(24, 3), h: 1 + buf.readUIntLE(27, 3) };
    if (kind === "VP8 ") return { w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
    if (kind === "VP8L") { const b = buf.readUInt32LE(21); return { w: 1 + (b & 0x3fff), h: 1 + ((b >> 14) & 0x3fff) }; }
  }
  if (buf.readUInt32BE(0) === 0x89504e47) return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    for (let i = 2; i < buf.length - 9;) {
      if (buf[i] !== 0xff) { i++; continue; }
      const m = buf[i + 1], len = buf.readUInt16BE(i + 2);
      if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) return { w: buf.readUInt16BE(i + 7), h: buf.readUInt16BE(i + 5) };
      i += 2 + len;
    }
  }
  return null;
}

export function sizesOf(index, dir = LIB_DIR) {
  const sizes = {};
  for (const t of Object.values(index)) for (const f of Object.values(t)) { const s = imageSize(readFileSync(join(dir, f))); if (s) sizes[f] = [s.w, s.h]; }
  return sizes;
}

export function indexModule(index, sizes = {}) {
  return `// GENERATED by hosting/scripts/upload-library.mjs from sitemaker/library. Do not edit; run the script after adding pictures.\n// trade -> slotId -> path under /library/ (and R2 library/).\nexport const LIBRARY_INDEX = ${JSON.stringify(index, null, 1)};\n// path -> [width, height]\nexport const LIBRARY_SIZES = ${JSON.stringify(sizes)};\n`;
}

function main() {
  const argv = process.argv.slice(2);
  const where = argv.includes("--remote") ? "--remote" : argv.includes("--local") ? "--local" : null;
  const index = scanLibrary();
  writeFileSync(INDEX_FILE, indexModule(index, sizesOf(index)));
  const files = Object.values(index).flatMap((t) => Object.values(t));
  const bytes = files.reduce((n, f) => n + statSync(join(LIB_DIR, f)).size, 0);
  console.log(`index: ${INDEX_FILE} (${files.length} pictures, ${(bytes / 1048576).toFixed(1)} MB, ${Object.keys(index).length} trades)`);
  const cmd = (f, w) => ["npx", "wrangler", "r2", "object", "put", `headroom-sites/library/${f}`, w, "--file", join(LIB_DIR, f), "--content-type", TYPES[f.split(".").pop().toLowerCase()], "--cache-control", CACHE];
  if (!where) {
    console.log("No upload (add --local or --remote). Commands, run from hosting/:");
    for (const f of files) console.log("  " + cmd(f, "--remote").map((x) => (/\s/.test(x) ? JSON.stringify(x) : x)).join(" "));
    return;
  }
  let bad = 0;
  for (const f of files) {
    const r = spawnSync(cmd(f, where)[0], cmd(f, where).slice(1), { cwd: root, encoding: "utf8" });
    console.log(`${r.status === 0 ? "ok  " : "FAIL"} library/${f}`);
    if (r.status !== 0) { bad++; console.log((r.stderr || r.stdout || "").trim().split("\n").slice(-3).join("\n")); }
  }
  console.log(bad ? `${bad} failed` : `uploaded ${files.length} (${where})`);
  process.exit(bad ? 1 : 0);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
